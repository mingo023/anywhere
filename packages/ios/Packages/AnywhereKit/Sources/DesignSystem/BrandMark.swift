    static func parse(_ d: String) -> Path {
        var path = Path()
        var command: Character = "M"
        var numbers: [CGFloat] = []
        func flush() {
            let p = stride(from: 0, to: numbers.count - 1, by: 2).map { CGPoint(x: numbers[$0], y: numbers[$0 + 1]) }
            switch command {
            case "M": path.move(to: p[0])
            case "L": path.addLine(to: p[0])
            case "C": path.addCurve(to: p[2], control1: p[0], control2: p[1])
            default: path.closeSubpath()
            }
            numbers = []
        }
        for token in d.split(whereSeparator: \.isWhitespace) {
            var token = Substring(token)
            if let first = token.first, first.isLetter {
                command = first
                token = token.dropFirst()
                if command == "Z" { flush() }
            }
            if let n = Double(token) { numbers.append(n) }
            if numbers.count == (command == "C" ? 6 : 2) { flush() }
        }
        return path
    }
