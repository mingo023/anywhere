import SwiftUI

/// An agent's brand mark, the desktop's: Claude's in its orange, Codex's (OpenAI's) in the ink around it.
@MainActor
public struct BrandMark: View {
    let provider: String
    let size: CGFloat

    public init(_ provider: String, size: CGFloat = 13) {
        self.provider = provider
        self.size = size
    }

    public var body: some View {
        Group {
            switch provider {
            case "claude": Mark(shape: Mark.claude).fill(Palette.agentClaude.color)
            case "codex": Mark(shape: Mark.openai).fill(.foreground)
            default: Image(systemName: "sparkle").resizable().scaledToFit().foregroundStyle(Palette.text3.color)
            }
        }
        .frame(width: size, height: size)
        .accessibilityHidden(true)
    }
}

