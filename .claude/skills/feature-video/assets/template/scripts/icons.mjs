// Writes src/video/icons.gen.ts from the app's icon set, #000 → currentColor so `<Icon color>` tints them.
// Run: node scripts/icons.mjs <repo>/packages/desktop/crates/theme/assets/icons
import fs from "node:fs";
import path from "node:path";

const dir = process.argv[2];
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".svg"))) {
  let s = fs.readFileSync(path.join(dir, f), "utf8").replace(/<!--.*?-->/gs, "").trim();
  s = s.replace(/#000000|#000\b/g, "currentColor").replace(/ width="\d+" height="\d+"/, ' width="100%" height="100%"');
  const root = s.split(">")[0];
  if (!/stroke=|fill=/.test(root)) s = s.replace("<svg ", '<svg fill="currentColor" ');
  out[f.slice(0, -4)] = s;
}
fs.writeFileSync(
  "src/video/icons.gen.ts",
  `// Generated by scripts/icons.mjs from packages/desktop/crates/theme/assets/icons (lucide, ISC).\nexport const ICONS: Record<string, string> = ${JSON.stringify(out)};\n`,
);
console.log(`${Object.keys(out).length} icons`);
